// Этап 4: параллельный блочный метод Холецкого на MPI (циклическое распределение блочных строк, distribution.hpp).
//
// Шаг j: строка j нужна всем процессам — её владелец рассылает её (MPI_Bcast), после чего каждый процесс считает свои
// блоки L_ij, i > j. Порядок операций в каждом блоке — как в последовательной программе, поэтому при любом числе
// процессов результат совпадает с ней побитно.
#pragma once

#include <mpi.h>

#include <vector>

#include "cli.hpp"
#include "distribution.hpp"

namespace lab4 {

// Разложение распределённой матрицы: каждый процесс вызывает со своими строками m (те же n, b, P). Если матрица не
// положительно определённа, NotPositiveDefinite бросают все процессы на одном и том же шаге (признак ошибки
// рассылается вместе с L_jj), поэтому никто не остаётся ждать рассылки.
//   block  — владелец строки j: Ã_jj и L_jj; рассылка строки j целиком; остальные — свои Ã_ij и L_ij;
//   phases — рассылка L_j0 … L_j,j−1 (известны с прошлого шага); все одновременно — свои Ã_ij, владелец — и Ã_jj;
//            владелец: L_jj; рассылка L_jj; все — свои L_ij.
void cholesky_distributed(BlockRows& m, Mode mode, MPI_Comm comm);

// max |L − L_точн| по всей матрице — одинаковое значение на всех процессах.
double max_error_distributed(const BlockRows& m, MPI_Comm comm);

// Фактор L целиком (n×n по строкам) на процессе 0; на остальных — пустой вектор. Только для проверок.
std::vector<double> gather_factor(const BlockRows& m, MPI_Comm comm);

}  // namespace lab4
